/**
 * П5: «Диета» для текста страницы перед отправкой в интерактивные ИИ-задачи
 * Sidekick (саммари, верификация, карточка интервью, чат).
 *
 * Меньше входных токенов → быстрее первый токен и дешевле запрос.
 * Фильтр КОНСЕРВАТИВНЫЙ: вырезаем только заведомый боилерплейт hh.ru
 * (навигация, футер, служебные ссылки) построчно — содержимое резюме
 * и вакансий не трогаем. Скрининговый контур (autoScore/structureResume)
 * этим модулем не пользуется.
 */

/** Строки-шум: точные (после trim, без учёта регистра) вхождения боилерплейта hh.ru. */
const NOISE_LINES = new Set([
  'все сервисы',
  'поиск сотрудников',
  'каталог резюме',
  'похожие резюме',
  'помощь',
  'соискателям',
  'работодателям',
  'разместить вакансию',
  'создать резюме',
  'войти',
  'регистрация',
  'меню',
  'наверх',
  'напишите нам',
  'горячие вакансии',
  'вакансии дня',
  'работа рядом с домом',
  'уведомления',
  'избранное',
  'отклики и приглашения',
  'мои резюме',
].map(s => s.toLowerCase()))

/** Строки-шум: паттерны (копирайт, счётчики и т.п.). */
const NOISE_PATTERNS: RegExp[] = [
  /^©\s*2000[–-]20\d{2}.*headhunter/i,
  /^©\s*headhunter/i,
  /^группа компаний headhunter$/i,
  /^сегодня в \d/i,
  /^показать контакты$/i,
  /^\d+\s+(похожих?\s+)?резюме$/i,
]

function isNoiseLine(line: string): boolean {
  const t = line.trim().toLowerCase()
  if (!t) return false
  if (NOISE_LINES.has(t)) return true
  return NOISE_PATTERNS.some(re => re.test(t))
}

/**
 * Подготовить текст страницы для интерактивного ИИ-запроса:
 * 1) убрать построчно известный боилерплейт hh.ru;
 * 2) схлопнуть повторные пробелы/табы и пустые строки;
 * 3) обрезать до `limit` символов.
 */
export function prepareInteractiveText(raw: string, limit: number): string {
  const lines = raw.split('\n').filter(line => !isNoiseLine(line))
  return lines
    .join('\n')
    .replace(/[ \t]+/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
    .slice(0, limit)
}
